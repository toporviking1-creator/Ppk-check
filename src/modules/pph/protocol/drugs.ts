export interface DoseSuggestion {
  /** Текст рекомендации с учётом массы. */
  text: string;
  /** Значения по умолчанию для быстрой записи введения. */
  dose: number;
  unit: string;
  route: string;
  volumeMl?: number;
}

export interface DrugDef {
  id: string;
  name: string;
  group: 'Утеротоники' | 'Гемостаз' | 'Компоненты крови' | 'Инфузия' | 'Анестезия и ИТ' | 'Профилактика';
  ref: string;
  suggest: (weightKg?: number) => DoseSuggestion;
  /** Предупреждения/противопоказания. */
  cautions?: string[];
  /** Пункт чек-листа, отмечаемый при записи введения. */
  checklistItem?: string;
}

const round = (v: number, step = 1) => Math.round(v / step) * step;

function perKg(weightKg: number | undefined, mgPerKg: number, fallback: number, step = 1): number {
  return weightKg ? round(weightKg * mgPerKg, step) : fallback;
}

