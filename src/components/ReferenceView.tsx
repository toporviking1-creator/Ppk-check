function AtlasItem(props: { p: Pattern }) {
  const t = useMemo(() => generateTrace(props.p.frames, props.p.minutes, props.p.seed), [props.p]);
  const px = props.p.minutes > 20 ? 12 : props.p.minutes > 12 ? 18 : 26;
  return (
    <div className="type-card">
      <h4>{props.p.title}</h4>
      <div className="mini-strip">
        <StaticStrip fhr={t.fhr} toco={t.toco} hz={t.hz} minutes={props.p.minutes} pxPerMin={px} fhrHeight={150} tocoHeight={45} />
      </div>
      <p className="small muted">{props.p.text}</p>
    </div>
  );
}

