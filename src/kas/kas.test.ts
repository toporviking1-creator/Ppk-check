describe('разбор эпикриза', () => {
  const epi = parseEpicrisis(EPICRISIS);

  it('читает шапку и сведения о пациенте', () => {
    expect(epi.fio).toBe('Иванова Мария Петровна');
    expect(epi.historyNo).toBe('123456-26-С');
    expect(epi.docType).toBe('ЭТАПНЫЙ ЭПИКРИЗ');
    expect(epi.birthDate).toBe('01.02.1990');
    expect(epi.age).toBe('36 лет');
    expect(epi.admission).toBe('10.09.2026 08:30');
  });

  it('не принимает «Заключение» внутри УЗИ и анамнез внутри текущего состояния за новые разделы', () => {
    const keys = epi.sections.map((s) => s.key);
    expect(keys).not.toContain('conclusion');
    expect(keys.filter((k) => k === 'gyn')).toHaveLength(1);
    expect(keys).toContain('meds');
    expect(keys.at(-1)).toBe('status');
  });

  it('разбирает диагнозы и предлагает название КАС', () => {
    const dx = parseDiagnoses(epi.sections.find((s) => s.key === 'diagnosis')!.lines);
    expect(dx.map((g) => g.kind)).toEqual(['main', 'complication', 'concomitant']);
    expect(dx[0].items[0]).toEqual({ code: 'O47.0', text: 'Беременность 30 недель 2 дня. Головное предлежание. Угроза преждевременных родов' });
    expect(suggestTitle(dx)).toBe('Преждевременная отслойка нормально расположенной плаценты');
  });

  it('понимает диагноз в формате бланка КАС (код в конце, заголовки без двоеточия)', () => {
    const dx = parseDiagnoses([
      'Клинический Основной',
      '1 своевременные оперативные роды. Кесарево сечение. (O82.1)',
      'Клинический Осложнение основного',
      'Преждевременная отслойка нормально расположенной плаценты. (O45.8)',
    ]);
    expect(dx.map((g) => g.kind)).toEqual(['main', 'complication']);
    expect(dx[1].items[0].code).toBe('O45.8');
  });
});

describe('лабораторная сводка', () => {
  const epi = parseEpicrisis(EPICRISIS);
  const labs = summarizeLabs(epi.sections.find((s) => s.key === 'labs')!.lines);

  it('собирает ключевые показатели по дате с отметкой отклонений', () => {
    expect(labs[0]).toContain('10.09.2026: Гемоглобин – 98,0 г/л ↓');
    expect(labs[0]).toContain('Гематокрит – 29,10% ↓');
    expect(labs[0]).toContain('Тромбоциты – 180,00 ×10^9/л;');
    expect(labs[0]).toContain('Лейкоциты – 11,20 ×10^9/л ↑');
    expect(labs[0]).toContain('МНО – 1,02');
    expect(labs[0]).toContain('Фибриноген – 3,10 г/л');
    expect(labs[0]).toContain('Белок в моче – 0,05 г/л');
    // Лейкоциты мочи не путаются с лейкоцитами крови.
    expect(labs[0].match(/Лейкоциты/g)).toHaveLength(1);
  });

  it('группа крови, резус, инфекции', () => {
    expect(labs).toContain('Группа крови: A(II) вторая, резус-фактор: Rh+ (положительный).');
    expect(labs).toContain('ВИЧ, HBsAg – отрицательно.');
  });
});

describe('формирование КАС', () => {
  const kas = buildKas(parseEpicrisis(EPICRISIS), { org: 'Перинатальный центр' });
  const row = (id: string) => kas.rows.find((r) => r.id === id)!.text;

  it('заполняет строки бланка', () => {
    expect(kas.title).toBe('Преждевременная отслойка нормально расположенной плаценты');
    expect(row('fio')).toBe('Иванова Мария Петровна');
    expect(row('patient')).toBe('Дата рождения: 01.02.1990 (36 лет)\nДата поступления в стационар: 10.09.2026 08:30');
    expect(row('diagnosis')).toContain('# Осложнение основного\nПреждевременная отслойка нормально расположенной плаценты (O45.8)');
    expect(row('complaints')).toBe('на кровянистые выделения из половых путей, боли внизу живота');
    expect(row('life')).toContain('Перенесенные операции: аппендэктомия в 2010 г.');
    expect(row('life')).toContain('Вредные привычки: нет.');
    expect(row('gyn').split('\n')).toHaveLength(4);
  });

  it('инструментальные исследования — заключения без дисклеймеров и рекомендаций', () => {
    expect(row('instr')).toBe(
      [
        '# Ультразвуковое исследование плода 10.09.2026 09:00',
        'Заключение: Беременность 30 нед. Ретроплацентарная гематома.',
        '# УЗ-допплерография маточно-плацентарного кровотока 10.09.2026 09:10',
        'Заключение: Нарушений гемодинамики не выявлено.',
      ].join('\n'),
    );
    const full = buildKas(parseEpicrisis(EPICRISIS), { org: '', instrMode: 'full' }).rows.find((r) => r.id === 'instr')!.text;
    expect(full).toContain('ретроплацентарная гематома 40*20 мм');
    expect(full).not.toContain('Данное заключение');
    expect(full).not.toContain('Рекомендация консультации');
  });

  it('лечение — по одной строке на назначение', () => {
    expect(row('treatment').split('\n')).toEqual([
      '10.09.2026: Транексамовая кислота 1000 мг. В/В, однократно, 09:00 ч., 1 день — гемостатическая терапия',
      '10.09.2026–12.09.2026: Нифедипин 10 мг. Перорально, 4 раза в сутки, 3 дня',
    ]);
  });

  it('текущее состояние без дублированного анамнеза', () => {
    expect(row('status')).toBe(
      [
        '# Общие сведения',
        'Общее состояние: средней тяжести. Сознание: ясное.',
        '# Состояние сердечно-сосудистой системы',
        'Систолическое давление: 110 мм.рт.ст.; Диастолическое давление: 70 мм.рт.ст.; Частота пульса: 88 /мин;',
        '# Выделения',
        'Патологические выделения из половых путей: есть. Характер: кровянистые.',
      ].join('\n'),
    );
  });

  it('пропускает строки без данных', () => {
    const ids = filledRows(kas).map((r) => r.id);
    expect(ids).not.toContain('history');
    expect(ids).not.toContain('operations');
    expect(ids).not.toContain('conclusion');
    expect(kasToPlainText(kas)).not.toContain('АНАМНЕЗ ЗАБОЛЕВАНИЯ');
  });

  it('выгружается в Word', async () => {
    const zip = await JSZip.loadAsync(await Packer.toBuffer(buildKasDocument(kas)));
    const xml = await zip.file('word/document.xml')!.async('string');
    expect(xml).toContain('Извещение о критическом акушерском состоянии (КАС)');
    expect(xml).toContain('Перинатальный центр');
    expect(xml).toContain('Иванова Мария Петровна');
    expect(xml).toContain('Гемоглобин – 98,0 г/л ↓');
    expect(xml).not.toContain('Анамнез заболевания');
    expect(kasFileName(kas, new Date(2026, 8, 11))).toBe('КАС_Иванова_11.09.2026.docx');
  });
});

describe('извлечение текста', () => {
  it('PDF: строки по признаку конца строки и по смене вертикали', () => {
    const text = pdfItemsToText([
      [
        { str: 'Гемоглобин общий', transform: [1, 0, 0, 1, 50, 500] },
        { str: ' ', transform: [1, 0, 0, 1, 140, 500] },
        { str: '118,1', transform: [1, 0, 0, 1, 290, 498], hasEOL: false },
        { str: 'Гематокрит', transform: [1, 0, 0, 1, 50, 480] },
      ],
    ]);
    expect(text).toBe('Гемоглобин общий 118,1\nГематокрит\n');
  });

  it('DOCX: абзацы и ячейки таблиц — отдельными строками', () => {
    const xml =
      '<w:document><w:body><w:p><w:r><w:t>Жалобы</w:t></w:r></w:p><w:tbl><w:tr><w:tc><w:p><w:r><w:t xml:space="preserve">на боли &amp; </w:t></w:r><w:r><w:t>выделения</w:t></w:r></w:p></w:tc></w:tr></w:tbl></w:body></w:document>';
    expect(docxXmlToText(xml)).toBe('Жалобы\nна боли & выделения');
  });
});
